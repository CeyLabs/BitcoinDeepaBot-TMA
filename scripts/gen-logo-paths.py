"""Regenerates src/components/ui/logo-paths.ts from public/BDLogo_White.svg
(the hand-drawn landing logo). Needs: pip install svgpathtools
Usage: python3 scripts/gen-logo-paths.py

Each closed outline is cut at its point nearest to where the drawing starts
(the eyes for the mask, the left edge for each letter) and at the point
halfway round from there, giving two open strokes that both start at that
point: traced together they grow outward and meet on the far side."""
import json, math, re
from svgpathtools import Path, parse_path

src = open("public/BDLogo_White.svg").read()
paths = re.findall(r'<path class="([^"]*)" d="([^"]*)"', src)
mask = next(d for c, d in paths if c == "cls-3")
ink = [d for c, d in paths if c == "cls-1"]
orange = [d for c, d in paths if c == "cls-2"]
EYES = complex(271.9, 443.5)  # between the two pupils


def pieces(d):
    # Every outline starts with an absolute M, so the string splits as-is.
    return ["M" + p for p in d.split("M") if p.strip()]


def pt(z):
    return f"{round(z.real)} {round(z.imag)}"


def compact(p):
    """Relative, whole-unit path data (1 unit is about a quarter pixel on
    screen), without the near-zero segments the cuts leave behind."""
    segs = [s for s in p if s.length() >= 1.5] or list(p)[:1]
    cur = complex(round(segs[0].start.real), round(segs[0].start.imag))
    out = "M" + pt(cur)
    last = ""
    for s in segs:
        if hasattr(s, "control2"):
            cmd, zs = "c", (s.control1, s.control2, s.end)
        elif hasattr(s, "control"):
            cmd, zs = "q", (s.control, s.end)
        else:
            cmd, zs = "l", (s.end,)
        rel = [complex(round(z.real), round(z.imag)) - cur for z in zs]
        nums = " ".join(f"{int(z.real)} {int(z.imag)}" for z in rel)
        out += (cmd if cmd != last else " ") + nums
        last = cmd
        cur += rel[-1]
    return re.sub(r" -", "-", out)


def halves(d, nearest_to):
    sp = parse_path(d)
    samples = [i / 400 for i in range(400)]
    t0 = min(samples, key=nearest_to(sp))
    rot = Path(*(list(sp.cropped(t0, 1)) + list(sp.cropped(0, t0)))) if t0 > 0 else sp
    total = rot.length()
    th = rot.ilength(total / 2)
    a, b = rot.cropped(0, th), rot.cropped(th, 1).reversed()
    return [(compact(a), max(1, round(a.length()))), (compact(b), max(1, round(b.length())))], sp


def nearest_eyes(sp):
    return lambda t: abs(sp.point(t) - EYES)


def leftmost(sp):
    return lambda t: sp.point(t).real


mask_rows = []
for d in pieces(mask):
    hs, sp = halves(d, nearest_eyes)
    xmin, xmax, ymin, ymax = sp.bbox()
    dist = abs(complex((xmin + xmax) / 2, (ymin + ymax) / 2) - EYES)
    mask_rows += [[h, l, dist] for h, l in hs]
far = max(r[2] for r in mask_rows)
for r in mask_rows:
    r[2] = round(r[2] / far, 3)
mask_rows.sort(key=lambda r: r[2])

word_rows = []
for kind, group in (("ink", ink), ("orange", orange)):
    for d in group:
        for piece in pieces(d):
            hs, sp = halves(piece, leftmost)
            word_rows += [[h, l, sp.bbox()[0], kind] for h, l in hs]
x0 = min(r[2] for r in word_rows)
x1 = max(r[2] for r in word_rows)
for r in word_rows:
    r[2] = round((r[2] - x0) / (x1 - x0), 3)
word_rows.sort(key=lambda r: r[2])

out = [
    "/* Generated by scripts/gen-logo-paths.py from public/BDLogo_White.svg",
    "   (BDLogo_Black.svg has the same paths). Don't edit by hand. */",
    "",
    'export const LOGO_VIEWBOX = "0 0 543.84 865.92";',
    "/** The Yaka mask as one path (its outlines cut holes in each other). */",
    "export const MASK_FILL = " + json.dumps(mask) + ";",
    "/** Strokes tracing the mask: [d, length, t], t = 0 at the eyes to 1 for",
    "    the farthest outline. Two per outline, both starting at its point",
    "    nearest the eyes, so the lines grow outward. */",
    "export const MASK_LINES: [d: string, length: number, t: number][] = "
    + json.dumps(mask_rows) + ";",
    '/** "bitcoin" (white on dark, black on light). */',
    "export const WORDMARK_INK: string[] = " + json.dumps(ink) + ";",
    "/** දීප, always brand orange. */",
    "export const WORDMARK_ORANGE: string[] = " + json.dumps(orange) + ";",
    "/** Strokes tracing the wordmark letter by letter: [d, length, t, colour],",
    "    t = 0 at the left edge to 1 at the right. */",
    'export const WORD_LINES: [d: string, length: number, t: number, kind: "ink" | "orange"][] = '
    + json.dumps(word_rows) + ";",
    "",
]
open("src/components/ui/logo-paths.ts", "w").write("\n".join(out))
print(len(mask_rows), "mask strokes,", len(word_rows), "wordmark strokes")
