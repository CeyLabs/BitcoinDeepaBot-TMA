"""Regenerates src/components/ui/logo-paths.ts from public/BDLogo_White.svg
(the animated landing logo). Needs: pip install svgpathtools
Usage: python3 scripts/gen-logo-paths.py"""
import json, math, re
from svgpathtools import parse_path

src = open("public/BDLogo_White.svg").read()
paths = re.findall(r'<path class="([^"]*)" d="([^"]*)"', src)
mask = next(d for c, d in paths if c == "cls-3")
ink = [d for c, d in paths if c == "cls-1"]
orange = [d for c, d in paths if c == "cls-2"]

# Every piece of the mask starts with an absolute M, so it splits as-is.
pieces = ["M" + p for p in mask.split("M") if p.strip()]
EYES = (271.9, 443.5)  # between the two pupils
rows = []
for d in pieces:
    sp = parse_path(d)
    xmin, xmax, ymin, ymax = sp.bbox()
    dist = math.hypot((xmin + xmax) / 2 - EYES[0], (ymin + ymax) / 2 - EYES[1])
    rows.append([d, max(1, round(sp.length())), dist])
far = max(r[2] for r in rows)
for r in rows:
    r[2] = round(r[2] / far, 3)
rows.sort(key=lambda r: r[2])

out = [
    "/* Generated by scripts/gen-logo-paths.py from public/BDLogo_White.svg",
    "   (BDLogo_Black.svg has the same paths). Don't edit by hand. */",
    "",
    'export const LOGO_VIEWBOX = "0 0 543.84 865.92";',
    "/** The Yaka mask, one entry per closed piece: [d, length, t], t = distance",
    "    from the eyes (0) to the farthest piece (1), sorted by t. Joined they",
    "    make the original compound path (its pieces cut holes in each other). */",
    "export const MASK_PIECES: [d: string, length: number, t: number][] = "
    + json.dumps(rows) + ";",
    '/** "bitcoin" (white on dark, black on light). */',
    "export const WORDMARK_INK: string[] = " + json.dumps(ink) + ";",
    "/** දීප, always brand orange. */",
    "export const WORDMARK_ORANGE: string[] = " + json.dumps(orange) + ";",
    "",
]
open("src/components/ui/logo-paths.ts", "w").write("\n".join(out))
print(len(rows), "pieces")
